# Задание.1
countries = {
    "Россия": "Москва",
    "Франция": "Париж",
    "Германия": "Берлин",
    "Италия": "Рим",
    "Япония": "Токио",
    "Китай": "Пекин",
    "Испания": "Мадрид"
}
print("Все пары страна-столица:")
for country, capital in countries.items():
    print(f'{country} — {capital}')

country_inp = input("\nВведите название страны, чтобы узнать её столицу: ")
capital = countries.get(country_inp, 'не найдена')
print(f'Столица страны {country_inp}: {capital}')

print("Содержимое словаря в алфавитном порядке названий стран:")
for country in sorted(countries):               # sorted() создаёт временный список, но не сохраняет
    print(f'{country} — {countries[country]}')

